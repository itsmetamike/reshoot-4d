"""Super recipe, face stage: re-render the face of an LTX pass at crop resolution and paste it back.

The face box comes from the capture's own 3D head track projected through the Director camera (no detector: steady box, works
when the dancer turns away). Each frame's square crop (fixed size per run) is upscaled to 768x768 and regenerated by LTX 2.3 with
  control = the crop itself (canny through the union IC-LoRA, or raw through a restoration IC-LoRA such as Deblur)
  anchors = the same head point projected into the nearest training camera's generated view, cropped the same way
then colour-matched to the original crop and feathered back in with an oval mask.
Usage: face_pass.py path.json train_dir upstream_result ltx.mp4 out.mp4 "who" [canny|deblur]
  deblur: LTX 2.3 Deblur IC-LoRA, raw crop as the same-resolution reference, single stage, the card's DEBLUR prompt
  env ANCHORS=0 drops the training-view anchors (the chunk still starts from the previous chunk's last frame)
"""
import json, math, os, subprocess, sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

sys.path.insert(0, str(Path(__file__).resolve().parent.parent)); import ltx_graph as sg  # noqa: E402

path_json, train_dir, up_dir, ltx_mp4, out_mp4, who = sys.argv[1:7]
mode = sys.argv[7] if len(sys.argv) > 7 else "canny"
ANCHORS = os.environ.get("ANCHORS", "1") != "0"
DEBLUR_LORA = "ltx-2.3-22b-ic-lora-deblur-0.9.safetensors"
INP = Path("/data/comfy_input"); FW = FH = 768; FPS = 24
RW, RH, PADX = 720, 1280, 24          # splat render size and the pad that made it 768 wide for LTX
LW, LH = 768, 1280
FACE_DROP, FACE_SIZE = 0.03, float(os.environ.get("FACE_SIZE", 0.17))   # head-track -> face centre (down), crop side (training units)
PER = float(os.environ.get("PER", 4.0))
work = Path(out_mp4).resolve().with_suffix(""); work.mkdir(parents=True, exist_ok=True)
train, up = Path(train_dir), Path(up_dir)
fr = json.loads(Path(path_json).read_text())["frames"]; n = len(fr)
meta = json.loads((train / "preview_meta.json").read_text())
UP = np.array(meta["up"]); UP /= np.linalg.norm(UP)
head = np.array(meta["track"]["head"])


def head_at(s):
    x = s * (len(head) - 1)
    return np.array([np.interp(x, np.arange(len(head)), head[:, k]) for k in range(3)]) - UP * FACE_DROP


def smooth(a, sigma):
    k = np.exp(-0.5 * (np.arange(-3 * int(sigma), 3 * int(sigma) + 1) / sigma) ** 2); k /= k.sum()
    p = np.pad(a, ((len(k) // 2, len(k) // 2), (0, 0)), mode="edge")
    return np.stack([np.convolve(p[:, j], k, mode="valid") for j in range(a.shape[1])], 1)


def look_at(eye, tgt, roll):   # same as rig.look_at (OpenCV c2w rotation)
    z = tgt - eye; z /= np.linalg.norm(z); x = np.cross(z, UP); x /= np.linalg.norm(x); y = np.cross(z, x)
    if roll:
        r = math.radians(roll); x, y = x * math.cos(r) + y * math.sin(r), -x * math.sin(r) + y * math.cos(r)
    return np.stack([x, y, z], 1)


# ---- face box per output frame (centre px, side px) in the 768x1280 LTX frame
boxes = []
for f in fr:
    s, eye, tgt, roll, fov = f[0], np.array(f[1:4]), np.array(f[4:7]), f[7], f[8]
    R = look_at(eye, tgt, roll); p = head_at(s); q = R.T @ (p - eye)
    fy = RH / 2 / math.tan(math.radians(fov) / 2)
    boxes.append([fy * q[0] / q[2] + RW / 2 + PADX, fy * q[1] / q[2] + RH / 2, fy * FACE_SIZE / q[2]])
boxes = smooth(np.array(boxes), 6.0)
side = int(np.clip(np.percentile(boxes[:, 2], 90), 192, LW))   # frozen per run so the crop never breathes
cx = np.clip(boxes[:, 0], side / 2, LW - side / 2); cy = np.clip(boxes[:, 1], side / 2, LH - side / 2)
print(f"face crop side {side}px -> {FW} ({FW / side:.2f}x)", flush=True)

# ---- training cameras (training space) for the anchors
W2T = np.array(json.loads((train / "normalization.json").read_text())["world_to_training"])
cams = []
for c in json.loads((up / "cameras.json").read_text())["cameras"]:
    c2w = np.array(c["camera_to_world"], float); c2w[:3, 3] = W2T[:3, :3] @ c2w[:3, 3] + W2T[:3, 3]
    c2w[:3, :3] = W2T[:3, :3] @ c2w[:3, :3] / np.cbrt(np.linalg.det(W2T[:3, :3]))
    cams.append((c2w, np.array(c["K"], float), c["video"]))


def crop_sq(a, x, y, sd):
    pad = int(sd)
    img = Image.fromarray(np.pad(a, ((pad, pad), (pad, pad), (0, 0)), mode="edge"))
    return img.crop((int(x - sd / 2) + pad, int(y - sd / 2) + pad, int(x - sd / 2) + pad + int(sd), int(y - sd / 2) + pad + int(sd)))


def anchor(fi, name):
    s, eye, tgt, roll = fr[fi][0], np.array(fr[fi][1:4]), np.array(fr[fi][4:7]), fr[fi][7]
    zf = look_at(eye, tgt, roll)[:, 2]
    best = max(range(len(cams)), key=lambda i: float(cams[i][0][:3, 2] @ zf))
    c2w, K, video = cams[best]; p = head_at(s)
    w2c = np.linalg.inv(c2w); q = w2c[:3, :3] @ p + w2c[:3, 3]; u, v = (K @ (q / q[2]))[:2]
    sd = K[1, 1] * FACE_SIZE / q[2]
    png = work / f"{name}_full.png"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(up / video), "-vf", f"select=eq(n\\,{int(round(s * 120))})", "-frames:v", "1", str(png)], check=True)
    crop_sq(np.asarray(Image.open(png).convert("RGB")), u, v, sd).resize((FW, FH), Image.LANCZOS).save(INP / f"{name}.png")
    return f"{name}.png", best, sd


def read_video(p, w, h):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(p), "-f", "rawvideo", "-pix_fmt", "rgb24", "-"], capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.uint8).reshape(-1, h, w, 3)


def write_video(frames, p, w, h, crf=12):
    pr = subprocess.Popen(["ffmpeg", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{w}x{h}", "-r", str(FPS), "-i", "-",
                           "-c:v", "libx264", "-crf", str(crf), "-pix_fmt", "yuv420p", str(p)], stdin=subprocess.PIPE)
    for f in frames:
        pr.stdin.write(np.ascontiguousarray(f).tobytes())
    pr.stdin.close(); pr.wait()


src = read_video(ltx_mp4, LW, LH)[:n]
crops = [np.asarray(crop_sq(src[i], cx[i], cy[i], side).resize((FW, FH), Image.LANCZOS)) for i in range(len(src))]
write_video(crops, work / "face_crops.mp4", FW, FH)
if os.environ.get("DRY"):
    for k, fi in enumerate([0, n // 2]):
        a, b, sd = anchor(fi, f"fp_dry_{k}")
        Image.fromarray(np.hstack([crops[fi], np.asarray(Image.open(INP / a))])).save(work / f"dry_{k}.jpg")
        print(f"dry {k}: frame {fi} cam{b} anchor side {sd:.0f}px", flush=True)
    sys.exit(0)

if mode == "deblur":   # the trained dual-panel caption from the model card
    prompt = (f"Reference shows a close-up of {who}, heavily out of focus with soft defocused blur and no fine detail. Edited shows the same "
              f"scene in sharp focus with crisp detail and clean edges. DEBLUR a close-up of {who}. Subject identity, framing, and background "
              "geometry are identical to the reference; only focus and sharpness differ between reference and edited.")
else:
    prompt = (f"Photoreal close-up of {who}. Sharp natural detail in the eyes, lashes, brows, lips, skin texture and individual hair strands, "
              "soft even studio light. The face and framing follow the guide exactly. No text.")
outs, prev, t0 = [], None, 0.0
dur = len(crops) / FPS
while t0 < dur - 1e-6:
    k = len(outs); secs = min(PER, dur - t0)
    f0, fm, f1 = int(t0 * FPS), int((t0 + secs / 2) * FPS), min(len(crops) - 1, int((t0 + secs) * FPS) - 1)
    a0, b0, _ = anchor(f0, f"fp_{k}_0"); a1, b1, _ = anchor(fm, f"fp_{k}_1"); a2, b2, _ = anchor(f1, f"fp_{k}_2")
    print(f"face chunk {k}: t={t0:.2f}+{secs:.2f}s anchors cam{b0}/{b1}/{b2}", flush=True)
    ctrl = f"fp_ctrl_{Path(out_mp4).stem}_{k}.mp4"
    write_video(crops[f0:f0 + int(round(secs * FPS))], INP / ctrl, FW, FH)
    refs = [{"image": prev or a0, "at": "start", "strength": 0.8}, {"image": a1, "at": round(secs / 2, 3), "strength": 0.5},
            {"image": a2, "at": "end", "strength": 0.5}]
    if not ANCHORS:
        refs = [{"image": prev, "at": "start", "strength": 0.8}] if prev else []
    spec = {"prompt": prompt, "video": {"seconds": secs, "fps": FPS, "width": FW, "height": FH, "seed": 11},
            "control": {"video": ctrl, "type": "canny", "strength": 0.9, "lora_strength": 0.8}, "refs": refs,
            "prefix": f"sam3dbx/face_{Path(out_mp4).stem}_{k}"}
    if mode == "deblur":
        spec.update(single_stage=True, control={"video": ctrl, "type": "raw", "strength": 1.0, "lora_strength": 1.0, "lora_name": DEBLUR_LORA},
                    negative="worst quality, blurry, out of focus, defocused, soft, hazy, smeared, low detail, jittery, distorted, oversharpened, haloing, ringing")
    sg.free()
    r = sg.wait(sg.queue(sg.build(spec)), timeout=1800)
    vid = [f.get("fullpath") for o in r[3].values() for f in o.get("gifs", []) if str(f.get("fullpath", "")).endswith(".mp4")]
    print(f"face chunk {k}:", r[0], r[1], "s", flush=True)
    if r[0] != "success" or not vid:
        sys.exit(1)
    got = read_video(vid[0], FW, FH)[:int(round(secs * FPS))]
    outs.append(got); prev = f"fp_prev_{Path(out_mp4).stem}_{k}.png"; Image.fromarray(got[-1]).save(INP / prev)
    t0 += secs
faces = np.concatenate(outs)

# ---- paste back: per-frame mean/std colour match to the original crop, oval feathered mask
m = Image.new("L", (side, side), 0); ImageDraw.Draw(m).ellipse((side * 0.1, side * 0.06, side * 0.9, side * 0.94), fill=255)
mask = np.asarray(m.filter(ImageFilter.GaussianBlur(side * 0.07)), np.float32)[..., None] / 255
res = []
for i in range(len(faces)):
    f = np.asarray(Image.fromarray(faces[i]).resize((side, side), Image.LANCZOS), np.float32)
    x0, y0 = int(round(cx[i] - side / 2)), int(round(cy[i] - side / 2))
    base = src[i].astype(np.float32); o = base[y0:y0 + side, x0:x0 + side]
    f = (f - f.mean((0, 1))) / (f.std((0, 1)) + 1e-6) * o.std((0, 1)) + o.mean((0, 1))
    base[y0:y0 + side, x0:x0 + side] = o * (1 - mask) + f * mask
    res.append(base.clip(0, 255).astype(np.uint8))
write_video(res, out_mp4, LW, LH)
write_video([np.hstack([c, np.asarray(Image.fromarray(fc))]) for c, fc in zip(crops, faces)], work / "faces_sbs.mp4", FW * 2, FH)
print("OUT", out_mp4, flush=True)
